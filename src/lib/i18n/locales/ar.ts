// Arabic counts in six forms: one and two are whole phrases ("صفحة واحدة", "صفحتان"),
// 3–10 take the plural ("3 صفحات"), 11–99 the accusative singular ("11 تغييرًا"),
// 100 and up the genitive one ("100 تغيير"); zero takes its own phrase, else the plural.
const rules = new Intl.PluralRules('ar');
const num = (n: number) => n.toLocaleString('en-US');
const plural = (n: number, one: string, two: string, few: string, many: string, other = many, zero?: string) => {
  const c = rules.select(n);
  if (c === 'zero' && zero !== undefined) return zero;
  if (c === 'one') return one;
  if (c === 'two') return two;
  return `${num(n)} ${c === 'few' || c === 'zero' ? few : c === 'many' ? many : other}`;
};

